// Command normalize adjusts generated schemas for Vanguard's proto3 JSON.
package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"regexp"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

var protoType = regexp.MustCompile(` ?\(proto ([^)]+)\)$`)

func normalize(value any, kind string) {
	switch node := value.(type) {
	case []any:
		for _, child := range node {
			normalize(child, kind)
		}
	case map[string]any:
		if description, ok := node["description"].(string); ok {
			if match := protoType.FindStringSubmatch(description); match != nil {
				kind = match[1]
				node["description"] = protoType.ReplaceAllString(description, "")
				if node["description"] == "" {
					delete(node, "description")
				}
			}
		}
		if node["format"] == "int64" {
			node["type"] = "string"
			delete(node, "format")
			node["pattern"] = `^-?[0-9]+$`
			if kind == "uint64" || kind == "fixed64" {
				node["pattern"] = `^[0-9]+$`
			}
		}
		if node["format"] == "duration" {
			// JSON Schema duration is ISO 8601; protobuf uses fractional seconds.
			delete(node, "format")
			node["pattern"] = `^-?[0-9]+(\.[0-9]{1,9})?s$`
		}
		// Protobuf oneofs may be unset. Proto anyOf annotations enforce required choices.
		if branches, ok := node["oneOf"].([]any); ok {
			absent := map[string]any{}
			for _, branch := range branches {
				b, ok := branch.(map[string]any)
				if !ok || b["properties"] == nil || b["required"] == nil {
					absent = nil
					break
				}
				for name := range b["properties"].(map[string]any) {
					absent[name] = false
				}
			}
			if len(absent) > 0 {
				node["oneOf"] = append(branches, map[string]any{"properties": absent})
			}
		}
		// unevaluatedProperties recognizes fields declared in allOf/oneOf.
		if node["additionalProperties"] == false && (node["allOf"] != nil || node["oneOf"] != nil) {
			delete(node, "additionalProperties")
			node["unevaluatedProperties"] = false
		}
		for key, child := range node {
			if key == "schema" || key == "items" || key == "additionalProperties" {
				normalize(child, kind)
			} else {
				normalize(child, "")
			}
		}
	}
}

// pruneSchemas keeps schemas reachable from the REST operations and shared responses.
func pruneSchemas(spec map[string]any) {
	components := spec["components"].(map[string]any)
	schemas := components["schemas"].(map[string]any)
	delete(components, "schemas")
	used := map[string]any{}
	var visit func(any)
	visit = func(value any) {
		switch node := value.(type) {
		case []any:
			for _, child := range node {
				visit(child)
			}
		case map[string]any:
			if ref, ok := node["$ref"].(string); ok && strings.HasPrefix(ref, "#/components/schemas/") {
				name := strings.TrimPrefix(ref, "#/components/schemas/")
				if schema, exists := schemas[name]; exists {
					if _, seen := used[name]; !seen {
						used[name] = schema
						visit(schema)
					}
				}
			}
			for _, child := range node {
				visit(child)
			}
		}
	}
	visit(spec)
	components["schemas"] = used
}

func run(args []string) error {
	if len(args) != 2 {
		return errors.New("usage: normalize INPUT.json OUTPUT.yaml")
	}
	data, err := os.ReadFile(args[0]) //nolint:gosec // CLI argument specifies the input file.
	if err != nil {
		return err
	}
	var spec map[string]any
	if err := json.Unmarshal(data, &spec); err != nil {
		return err
	}
	normalize(spec, "")
	pruneSchemas(spec)
	var document yaml.Node
	if err := document.Encode(spec); err != nil {
		return err
	}
	// Keep the overview before the paths and schemas; nested maps remain sorted.
	var ordered []*yaml.Node
	sections := []string{"openapi", "info", "servers", "security", "tags", "paths", "components"}
	for _, name := range sections {
		for i := 0; i < len(document.Content); i += 2 {
			if document.Content[i].Value == name {
				ordered = append(ordered, document.Content[i:i+2]...)
			}
		}
	}
	for i := 0; i < len(document.Content); i += 2 {
		if !slices.Contains(sections, document.Content[i].Value) {
			ordered = append(ordered, document.Content[i:i+2]...)
		}
	}
	document.Content = ordered
	var out strings.Builder
	out.WriteString("# Code generated by make proto. DO NOT EDIT.\n")
	out.WriteString("# checkov:skip=CKV_OPENAPI_21:Vanguard does not impose maxItems on repeated cell filters.\n")
	enc := yaml.NewEncoder(&out)
	enc.SetIndent(2)
	if err := enc.Encode(&document); err != nil {
		return err
	}
	if err := enc.Close(); err != nil {
		return err
	}
	return os.WriteFile(args[1], []byte(out.String()), 0o644) //nolint:gosec // CLI argument specifies the output file.
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1) //nolint:forbidigo // Command entry point.
	}
}
