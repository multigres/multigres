func TestDiff_UnsupportedColumnChanges(t *testing.T) {
	tests := []struct {
		name     string
		from, to Column
	}{
		{"becomes identity", Column{Type: "bigint", NotNull: true}, Column{Type: "bigint", NotNull: true, Identity: ast.ATTRIBUTE_IDENTITY_ALWAYS}},
		{"identity kind", Column{Type: "bigint", NotNull: true, Identity: ast.ATTRIBUTE_IDENTITY_ALWAYS}, Column{Type: "bigint", NotNull: true, Identity: ast.ATTRIBUTE_IDENTITY_BY_DEFAULT}},
		{"becomes generated", Column{Type: "integer", Default: "1"}, Column{Type: "integer", Default: "1", Generated: true}},
		{"becomes serial", Column{Type: "bigint", NotNull: true, Default: "nextval('s'::regclass)"}, Column{Type: "bigint", NotNull: true, Default: "nextval('s'::regclass)", Serial: true}},
		{"generation expression", Column{Type: "integer", Default: "(a + 1)", Generated: true}, Column{Type: "integer", Default: "(a + 2)", Generated: true}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			tt.from.Name, tt.to.Name = "c", "c"
			_, err := Diff(schema(table("t", []*Column{&tt.from}, nil, nil)), schema(table("t", []*Column{&tt.to}, nil, nil)), Options{})
			require.Error(t, err)
			assert.Contains(t, err.Error(), "t.c")
			assert.Equal(t, mtrpcpb.Code_UNIMPLEMENTED, mterrors.Code(err))
		})
	}
}

func TestDiff_RekeyedTableRebuildsTheForeignKeysReferencingIt(t *testing.T) {
	fk := &Constraint{Name: "c_p_fkey", Type: ast.CONSTR_FOREIGN, Definition: "FOREIGN KEY (p) REFERENCES p(id)", References: "p"}
	child := table("c", []*Column{{Name: "p", Type: "bigint"}}, []*Constraint{fk}, nil)
	from := schema(child, table("p", []*Column{{Name: "id", Type: "bigint", NotNull: true}},
		[]*Constraint{{Name: "p_pkey", Type: ast.CONSTR_PRIMARY, Definition: "PRIMARY KEY (id)"}}, nil))
	to := schema(child, table("p", []*Column{{Name: "id", Type: "bigint", NotNull: true}, {Name: "v", Type: "integer"}},
		[]*Constraint{{Name: "p_pkey", Type: ast.CONSTR_PRIMARY, Definition: "PRIMARY KEY (id, v)"}}, nil))

	changes, err := Diff(from, to, Options{})
	require.NoError(t, err)
	assert.Equal(t, []string{
		"ALTER TABLE c DROP CONSTRAINT c_p_fkey",
		"ALTER TABLE p DROP CONSTRAINT p_pkey",
		"ALTER TABLE p ADD COLUMN v integer",
		"ALTER TABLE p ADD CONSTRAINT p_pkey PRIMARY KEY (id, v)",
		"ALTER TABLE c ADD CONSTRAINT c_p_fkey FOREIGN KEY (p) REFERENCES p(id)",
	}, sqls(changes))

	// A changed check constraint does not touch the foreign keys.
	to = schema(child, table("p", []*Column{{Name: "id", Type: "bigint", NotNull: true}},
		[]*Constraint{
			{Name: "p_pkey", Type: ast.CONSTR_PRIMARY, Definition: "PRIMARY KEY (id)"},
			{Name: "p_check", Type: ast.CONSTR_CHECK, Definition: "CHECK (id > 0)"},
		}, nil))
	changes, err = Diff(from, to, Options{})
	require.NoError(t, err)
	assert.Equal(t, []string{"ALTER TABLE p ADD CONSTRAINT p_check CHECK (id > 0)"}, sqls(changes))
}

func TestDiff_KeepExtraTablesRefusesAnExtraTableReferencingARekeyedTable(t *testing.T) {
	fk := &Constraint{Name: "c_p_fkey", Type: ast.CONSTR_FOREIGN, Definition: "FOREIGN KEY (p) REFERENCES p(id)", References: "p"}
	from := schema(
		table("c", []*Column{{Name: "p", Type: "bigint"}}, []*Constraint{fk}, nil),
		table("p", []*Column{{Name: "id", Type: "bigint", NotNull: true}},
			[]*Constraint{{Name: "p_pkey", Type: ast.CONSTR_PRIMARY, Definition: "PRIMARY KEY (id)"}}, nil))
	to := schema(table("p", []*Column{{Name: "id", Type: "bigint", NotNull: true}}, nil, nil))
	_, err := Diff(from, to, Options{KeepExtraTables: true})
	require.ErrorContains(t, err, "foreign key c_p_fkey of table c, which the target schema does not have, references table p")
	assert.Equal(t, mtrpcpb.Code_FAILED_PRECONDITION, mterrors.Code(err))
}

func TestDiff_DropsTheTablesOnlyInFrom(t *testing.T) {
	pkey := func(table string) *Constraint {
		return &Constraint{Name: table + "_pkey", Type: ast.CONSTR_PRIMARY, Definition: "PRIMARY KEY (id)"}
	}
	fk := func(name, refs string) *Constraint {
		return &Constraint{Name: name, Type: ast.CONSTR_FOREIGN, Definition: "FOREIGN KEY (r) REFERENCES " + refs + "(id)", References: refs}
	}
	cols := []*Column{{Name: "id", Type: "bigint", NotNull: true}, {Name: "r", Type: "bigint"}}
	from := schema(
		// a and b reference each other, a also references itself, and b
		// references p, whose key changes.
		table("a", cols, []*Constraint{pkey("a"), fk("a_b_fkey", "b"), fk("a_a_fkey", "a")}, nil),
		table("b", cols, []*Constraint{pkey("b"), fk("b_a_fkey", "a"), fk("b_p_fkey", "p")}, nil),
		// k stays and loses its foreign key into a.
		table("k", cols, []*Constraint{pkey("k"), fk("k_a_fkey", "a")}, nil),
		table("p", cols, []*Constraint{pkey("p")}, nil))
	to := schema(
		table("k", cols, []*Constraint{pkey("k")}, nil),
		table("p", cols, []*Constraint{{Name: "p_pkey", Type: ast.CONSTR_PRIMARY, Definition: "PRIMARY KEY (id, r)"}}, nil))

	changes, err := Diff(from, to, Options{})
	require.NoError(t, err)
	assert.Equal(t, []Change{
		{Table: "a", SQL: "ALTER TABLE a DROP CONSTRAINT a_b_fkey"},
		{Table: "b", SQL: "ALTER TABLE b DROP CONSTRAINT b_a_fkey"},
		{Table: "k", SQL: "ALTER TABLE k DROP CONSTRAINT k_a_fkey"},
		{Table: "a", SQL: "DROP TABLE a", Breaking: true},
		{Table: "b", SQL: "DROP TABLE b", Breaking: true},
		{Table: "p", SQL: "ALTER TABLE p DROP CONSTRAINT p_pkey"},
		{Table: "p", SQL: "ALTER TABLE p ADD CONSTRAINT p_pkey PRIMARY KEY (id, r)"},
	}, changes)

	// Keeping the extra tables, b's foreign key would pin p_pkey.
	_, err = Diff(from, to, Options{KeepExtraTables: true})
	require.ErrorContains(t, err, "foreign key b_p_fkey of table b")
}

func TestDiff_RefusesToCreateASerialColumn(t *testing.T) {
	serial := &Column{Name: "id", Type: "bigint", NotNull: true, Default: "nextval('t_id_seq'::regclass)", Serial: true}
	_, err := Diff(schema(), schema(table("t", []*Column{serial}, nil, nil)), Options{})
	require.ErrorContains(t, err, "column t.id is a serial column")
	assert.Equal(t, mtrpcpb.Code_UNIMPLEMENTED, mterrors.Code(err))
	_, err = Diff(schema(table("t", nil, nil, nil)), schema(table("t", []*Column{serial}, nil, nil)), Options{})
	require.ErrorContains(t, err, "column t.id is a serial column")
	// An existing serial column is compared like any other.
	s := schema(table("t", []*Column{serial}, nil, nil))
	changes, err := Diff(s, s, Options{})
	require.NoError(t, err)
	assert.Empty(t, changes)
}
