func schema(tables ...*Table) *Schema {
	s := &Schema{Tables: map[string]*Table{}}
	for _, t := range tables {
		s.Tables[t.Name] = t
	}
	return s
}

func table(name string, cols []*Column, cons []*Constraint, idx map[string]string) *Table {
	t := &Table{Name: name, Columns: cols, Constraints: map[string]*Constraint{}, Indexes: map[string]string{}}
	for _, c := range cons {
		t.Constraints[c.Name] = c
	}
	maps.Copy(t.Indexes, idx)
	return t
}

func sqls(changes []Change) []string {
	out := make([]string, len(changes))
	for i, c := range changes {
		out[i] = c.SQL
	}
	return out
}

func TestDiff_Identical(t *testing.T) {
	s := schema(table("t",
		[]*Column{{Name: "id", Type: "bigint", NotNull: true, Identity: ast.ATTRIBUTE_IDENTITY_ALWAYS}},
		[]*Constraint{{Name: "t_pkey", Type: ast.CONSTR_PRIMARY, Definition: "PRIMARY KEY (id)"}},
		map[string]string{"t_idx": "CREATE INDEX t_idx ON t USING btree (id)"}))
	changes, err := Diff(s, s, Options{})
	require.NoError(t, err)
	assert.Empty(t, changes)
}

func TestDiff_NewTableCreatesColumnsThenConstraintsThenForeignKeys(t *testing.T) {
	parent := table("a_parent",
		[]*Column{{Name: "id", Type: "bigint", NotNull: true, Identity: ast.ATTRIBUTE_IDENTITY_BY_DEFAULT}},
		[]*Constraint{{Name: "a_parent_pkey", Type: ast.CONSTR_PRIMARY, Definition: "PRIMARY KEY (id)"}}, nil)
	child := table("b_child",
		[]*Column{
			{Name: "parent_id", Type: "bigint", NotNull: true},
			{Name: "state", Type: "text", Default: "'new'::text"},
			{Name: "Weird", Type: "text COLLATE \"C\""},
		},
		[]*Constraint{
			{Name: "b_child_parent_id_fkey", Type: ast.CONSTR_FOREIGN, Definition: "FOREIGN KEY (parent_id) REFERENCES a_parent(id)"},
			{Name: "b_child_state_check", Type: ast.CONSTR_CHECK, Definition: "CHECK (state <> ''::text)"},
		},
		map[string]string{"b_child_state_idx": "CREATE INDEX b_child_state_idx ON b_child USING btree (state)"})

	changes, err := Diff(schema(), schema(parent, child), Options{})
	require.NoError(t, err)
	assert.Equal(t, []string{
		"CREATE TABLE a_parent (\n\tid bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL\n)",
		"CREATE TABLE b_child (\n\tparent_id bigint NOT NULL,\n\tstate text DEFAULT 'new'::text,\n\t\"Weird\" text COLLATE \"C\"\n)",
		"ALTER TABLE a_parent ADD CONSTRAINT a_parent_pkey PRIMARY KEY (id)",
		"ALTER TABLE b_child ADD CONSTRAINT b_child_state_check CHECK (state <> ''::text)",
		"CREATE INDEX b_child_state_idx ON b_child USING btree (state)",
		"ALTER TABLE b_child ADD CONSTRAINT b_child_parent_id_fkey FOREIGN KEY (parent_id) REFERENCES a_parent(id)",
	}, sqls(changes))
	for _, c := range changes {
		assert.False(t, c.Breaking, c.SQL)
	}
}

func TestDiff_ExistingTable(t *testing.T) {
	from := schema(table("t",
		[]*Column{
			{Name: "id", Type: "integer", NotNull: true},
			{Name: "gone", Type: "text"},
			{Name: "d", Type: "text", Default: "'x'::text"},
			{Name: "n", Type: "text", NotNull: true},
		},
		[]*Constraint{
			{Name: "t_fk", Type: ast.CONSTR_FOREIGN, Definition: "FOREIGN KEY (id) REFERENCES p(id)"},
			{Name: "t_check", Type: ast.CONSTR_CHECK, Definition: "CHECK (id > 0)"},
			{Name: "t_same", Type: ast.CONSTR_UNIQUE, Definition: "UNIQUE (id)"},
		},
		map[string]string{
			"t_old_idx":  "CREATE INDEX t_old_idx ON t USING btree (d)",
			"t_same_idx": "CREATE INDEX t_same_idx ON t USING btree (n)",
		}))
	to := schema(table("t",
		[]*Column{
			{Name: "id", Type: "bigint", NotNull: true},
			{Name: "d", Type: "text"},
			{Name: "n", Type: "text"},
			{Name: "added", Type: "jsonb", NotNull: true, Default: "'{}'::jsonb"},
		},
		[]*Constraint{
			{Name: "t_check", Type: ast.CONSTR_CHECK, Definition: "CHECK (id > 1)"},
			{Name: "t_same", Type: ast.CONSTR_UNIQUE, Definition: "UNIQUE (id)"},
		},
		map[string]string{
			"t_same_idx": "CREATE INDEX t_same_idx ON t USING btree (n)",
			"t_new_idx":  "CREATE INDEX t_new_idx ON t USING btree (added)",
		}))

	changes, err := Diff(from, to, Options{})
	require.NoError(t, err)
	assert.Equal(t, []Change{
		{Table: "t", SQL: "ALTER TABLE t DROP CONSTRAINT t_fk"},
		{Table: "t", SQL: "ALTER TABLE t DROP CONSTRAINT t_check"},
		{Table: "t", SQL: "DROP INDEX t_old_idx"},
		{Table: "t", SQL: "ALTER TABLE t DROP COLUMN gone", Breaking: true},
		{Table: "t", SQL: "ALTER TABLE t ALTER COLUMN id TYPE bigint", Breaking: true},
		{Table: "t", SQL: "ALTER TABLE t ALTER COLUMN d DROP DEFAULT"},
		{Table: "t", SQL: "ALTER TABLE t ALTER COLUMN n DROP NOT NULL"},
		{Table: "t", SQL: "ALTER TABLE t ADD COLUMN added jsonb DEFAULT '{}'::jsonb NOT NULL"},
		{Table: "t", SQL: "ALTER TABLE t ADD CONSTRAINT t_check CHECK (id > 1)"},
		{Table: "t", SQL: "CREATE INDEX t_new_idx ON t USING btree (added)"},
	}, changes)
}

