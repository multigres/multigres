// Package schemadiff checks schemadiff against a real PostgreSQL: each case
// creates a "have" and a "want" schema from DDL, diffs them, applies the diff
// to "have", and requires that a second diff is empty. Only the catalog can
// say what PostgreSQL normalizes two spellings of a table to, so none of this
// is something a unit test can check.
//
// The tests need the PostgreSQL server binaries and run in the integration
// job of CI. A machine without them skips; CI (CI=true) fails instead.
package schemadiff

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"testing"
	"time"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/multigres/multigres/go/common/mterrors"
	"github.com/multigres/multigres/go/common/pgprotocol/client"
	"github.com/multigres/multigres/go/common/schemadiff"
	"github.com/multigres/multigres/go/common/sqltypes"
	mtrpcpb "github.com/multigres/multigres/go/pb/mtrpc"
	"github.com/multigres/multigres/go/test/endtoend/pgbuilder"
)

const password = "schemadiff"

// conn adapts a client connection to schemadiff.Querier.
type conn struct{ *client.Conn }

func (c conn) QueryArgs(ctx context.Context, query string, args ...any) (*sqltypes.Result, error) {
	res, err := c.Conn.QueryArgs(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	if len(res) != 1 {
		return nil, fmt.Errorf("got %d results, want 1", len(res))
	}
	return res[0], nil
}

func TestDiffConverges(t *testing.T) {
	tests := []struct {
		name string
		have string
		want string
		// changes is the diff of have to want, as SQL.
		changes []string
	}{
		{
			name: "equivalent spellings",
			have: `CREATE TABLE p (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
				CREATE TABLE t (
					id     int PRIMARY KEY,
					name   varchar(10) NOT NULL UNIQUE,
					p_id   bigint REFERENCES p,
					state  text CHECK (state IN ('a', 'b')),
					at     timestamptz DEFAULT now()
				);
				CREATE INDEX t_state ON t (state) WHERE state = 'a'`,
			want: `CREATE TABLE p (id int8 GENERATED ALWAYS AS IDENTITY, PRIMARY KEY (id));
				CREATE TABLE t (
					id     integer NOT NULL,
					name   character varying(10) NOT NULL,
					p_id   int8,
					state  text,
					at     timestamp with time zone DEFAULT now(),
					PRIMARY KEY (id),
					UNIQUE (name),
					FOREIGN KEY (p_id) REFERENCES p (id),
					CHECK (state = ANY (ARRAY['a', 'b']))
				);
				CREATE INDEX t_state ON t USING btree (state) WHERE (state = 'a'::text)`,
		},
		{
			name: "new table referencing an existing one",
			have: `CREATE TABLE p (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY)`,
			want: `CREATE TABLE p (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
				CREATE TABLE c (
					id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
					p_id bigint NOT NULL REFERENCES p (id) ON DELETE CASCADE,
					role text NOT NULL CHECK (role IN ('primary', 'secondary')),
					name text COLLATE "C",
					UNIQUE (p_id, name)
				);
				CREATE UNIQUE INDEX c_one_primary ON c (p_id) WHERE role = 'primary'`,
			changes: []string{
				"CREATE TABLE c (\n\tid bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n\tp_id bigint NOT NULL,\n\trole text NOT NULL,\n\tname text COLLATE \"C\"\n)",
				"ALTER TABLE c ADD CONSTRAINT c_p_id_name_key UNIQUE (p_id, name)",
				"ALTER TABLE c ADD CONSTRAINT c_pkey PRIMARY KEY (id)",
				"ALTER TABLE c ADD CONSTRAINT c_role_check CHECK (role = ANY (ARRAY['primary'::text, 'secondary'::text]))",
				"CREATE UNIQUE INDEX c_one_primary ON c USING btree (p_id) WHERE role = 'primary'::text",
				"ALTER TABLE c ADD CONSTRAINT c_p_id_fkey FOREIGN KEY (p_id) REFERENCES p(id) ON DELETE CASCADE",
			},
		},
		{
			name: "column changes",
			have: `CREATE TABLE t (
					id   integer PRIMARY KEY,
					gone text,
					d    text DEFAULT 'x',
					n    text NOT NULL,
					m    text
				);
				INSERT INTO t (id, n, m) VALUES (1, 'n', 'm')`,
			want: `CREATE TABLE t (
					id    bigint PRIMARY KEY,
					d     text,
					n     text,
					m     text NOT NULL DEFAULT 'y',
					added jsonb NOT NULL DEFAULT '{}'
				)`,
			changes: []string{
				"ALTER TABLE t DROP COLUMN gone",
				"ALTER TABLE t ALTER COLUMN id TYPE bigint",
				"ALTER TABLE t ALTER COLUMN d DROP DEFAULT",
				"ALTER TABLE t ALTER COLUMN n DROP NOT NULL",
				"ALTER TABLE t ALTER COLUMN m SET DEFAULT 'y'::text",
				"ALTER TABLE t ALTER COLUMN m SET NOT NULL",
				"ALTER TABLE t ADD COLUMN added jsonb DEFAULT '{}'::jsonb NOT NULL",
			},
		},
		{
			name: "changed constraints and indexes are dropped and added again",
			have: `CREATE TABLE p (id bigint PRIMARY KEY);
				CREATE TABLE t (
					id    bigint PRIMARY KEY,
					p_id  bigint REFERENCES p,
					state text CHECK (state <> '')
				);
				CREATE INDEX t_state ON t (state);
				CREATE INDEX t_gone ON t (p_id)`,
			want: `CREATE TABLE p (id bigint PRIMARY KEY);
				CREATE TABLE t (
					id    bigint PRIMARY KEY,
					p_id  bigint REFERENCES p ON DELETE SET NULL,
					state text CHECK (state IN ('a', 'b'))
				);
				CREATE INDEX t_state ON t (state) WHERE state = 'a'`,
			changes: []string{
				"ALTER TABLE t DROP CONSTRAINT t_p_id_fkey",
				"ALTER TABLE t DROP CONSTRAINT t_state_check",
				"DROP INDEX t_gone",
				"DROP INDEX t_state",
				"ALTER TABLE t ADD CONSTRAINT t_state_check CHECK (state = ANY (ARRAY['a'::text, 'b'::text]))",
				"CREATE INDEX t_state ON t USING btree (state) WHERE state = 'a'::text",
				"ALTER TABLE t ADD CONSTRAINT t_p_id_fkey FOREIGN KEY (p_id) REFERENCES p(id) ON DELETE SET NULL",
			},
		},
	}

	ctx := t.Context()
	c := conn{dial(t, ctx, startPostgres(t), "postgres")}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Everything runs in one transaction that is rolled back, so
			// cases start from an empty database.
			run(t, ctx, c, "BEGIN")
			defer run(t, ctx, c, "ROLLBACK")
			run(t, ctx, c, "CREATE SCHEMA have; CREATE SCHEMA want")
			run(t, ctx, c, "SET LOCAL search_path = have; "+tt.have)
			run(t, ctx, c, "SET LOCAL search_path = want; "+tt.want)
			run(t, ctx, c, "SET LOCAL search_path = public")

			have, err := schemadiff.Introspect(ctx, c, "have")
			require.NoError(t, err)
			want, err := schemadiff.Introspect(ctx, c, "want")
			require.NoError(t, err)
			changes, err := schemadiff.Diff(have, want, schemadiff.Options{})
			require.NoError(t, err)
			got := make([]string, len(changes))
			for i, ch := range changes {
				got[i] = ch.SQL
			}
			assert.Equal(t, tt.changes, nilIfEmpty(got))

			run(t, ctx, c, "SET LOCAL search_path = have")
			for _, ch := range changes {
				run(t, ctx, c, ch.SQL)
			}
			run(t, ctx, c, "SET LOCAL search_path = public")

			have, err = schemadiff.Introspect(ctx, c, "have")
			require.NoError(t, err)
			again, err := schemadiff.Diff(have, want, schemadiff.Options{})
			require.NoError(t, err)
			assert.Empty(t, again, "the diff must converge")
		})
	}
}

func TestIntrospectRestoresSearchPath(t *testing.T) {
	ctx := t.Context()
	c := conn{dial(t, ctx, startPostgres(t), "postgres")}
	run(t, ctx, c, "BEGIN")
	defer run(t, ctx, c, "ROLLBACK")
	run(t, ctx, c, `SET LOCAL search_path = "$user", public`)
	_, err := schemadiff.Introspect(ctx, c, "missing")
	require.NoError(t, err)
	res, err := c.QueryArgs(ctx, "SHOW search_path")
	require.NoError(t, err)
	assert.Equal(t, `"$user", public`, string(res.Rows[0].Values[0]))
}

func TestIntrospectRequiresATransaction(t *testing.T) {
	ctx := t.Context()
	c := conn{dial(t, ctx, startPostgres(t), "postgres")}
	run(t, ctx, c, "CREATE SCHEMA s; CREATE TABLE s.t (id int)")
	_, err := schemadiff.Introspect(ctx, c, "s")
	require.ErrorContains(t, err, "must run inside a transaction")
	assert.Equal(t, mtrpcpb.Code_FAILED_PRECONDITION, mterrors.Code(err))
}

func TestIntrospectRefusesPartitionedTables(t *testing.T) {
	ctx := t.Context()
	c := conn{dial(t, ctx, startPostgres(t), "postgres")}
	run(t, ctx, c, "BEGIN")
	defer run(t, ctx, c, "ROLLBACK")
	run(t, ctx, c, "CREATE SCHEMA s; CREATE TABLE s.t (id int) PARTITION BY RANGE (id)")
	_, err := schemadiff.Introspect(ctx, c, "s")
	require.ErrorContains(t, err, "s.t is partitioned")
	assert.Equal(t, mtrpcpb.Code_UNIMPLEMENTED, mterrors.Code(err))
}

func nilIfEmpty(s []string) []string {
	if len(s) == 0 {
		return nil
	}
	return s
}

// run runs statements with the simple query protocol.
func run(t *testing.T, ctx context.Context, c conn, sql string) {
	t.Helper()
	_, err := c.Conn.Query(ctx, sql)
	require.NoError(t, err, sql)
}

// requireTools skips the test when it is run with -short or a tool is
// missing, and in CI fails it.
func requireTools(t *testing.T, names ...string) {
	t.Helper()
	if testing.Short() {
		t.Skip("runs PostgreSQL; skipped with -short")
	}
	for _, name := range names {
		if _, err := exec.LookPath(name); err != nil {
			if os.Getenv("CI") != "" {
				t.Fatalf("%s is not installed, and CI must run this test: %v", name, err)
			}
			t.Skipf("%s is not installed", name)
		}
	}
}

// startPostgres starts a throwaway postgres from the binaries on PATH and
// returns its port. Torn down via cleanup.
func startPostgres(t *testing.T) int {
	t.Helper()
	requireTools(t, "initdb", "postgres", "pg_isready")
	server, err := pgbuilder.StartInstalledStandalone(t, t.Context(), password)
	require.NoError(t, err)
	t.Cleanup(func() {
		_ = server.Stop()
		if t.Failed() {
			if data, err := os.ReadFile(server.LogPath); err == nil {
				t.Logf("postgres log:\n%s", data)
			}
		}
	})
	return server.Port
}

func dial(t *testing.T, ctx context.Context, port int, database string) *client.Conn {
	t.Helper()
	c, err := client.Connect(ctx, ctx, &client.Config{
		Host:        "127.0.0.1",
		Port:        port,
		User:        "postgres",
		Password:    password,
		Database:    database,
		SSLMode:     client.SSLModeDisable,
		DialTimeout: 5 * time.Second,
	})
	require.NoError(t, err)
	t.Cleanup(func() { c.Close() })
	return c
}
