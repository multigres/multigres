// TestCreateMigrationRejectsSecond proves only one migration is supported at a
// time: attempting to create a second migration while one already exists on
// the shard fails with a clear error, and the first migration is unaffected.
// The DDL-replication machinery (ddlrepl.go) is not namespaced per migration —
// a second concurrent migration would corrupt the first's ddl_log/
// ddl_capture_tables state — so Coordinator.CreateMigration rejects it
// up front rather than letting it corrupt shared state.
func TestCreateMigrationRejectsSecond(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping Multigres Migrator e2e in short mode")
	}
	if !utils.HasPostgreSQLBinaries() {
		t.Skip("PostgreSQL client/server binaries not on PATH")
	}
	ctx := t.Context()

	setup, cleanup := shardsetup.NewIsolated(t, shardsetup.WithMultipoolerCount(2))
	defer cleanup()
	primary := setup.GetPrimary(t)
	shardsetup.WaitForManagerReady(t, primary.Multipooler)
	targetDB := waitForPrimaryDB(t, ctx, setup)

	srcPort := startStandaloneSource(t)
	seedSource(t, ctx, srcPort) // public.orders
	sc := dialSource(t, ctx, srcPort)
	defer sc.Close()
	_, err := sc.Query(ctx, "CREATE TABLE public.widgets (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, w text)")
	require.NoError(t, err)

	mt, mtClose := migrationClient(t, primary)
	defer mtClose()

	id := createAndStartMigration(t, ctx, mt, srcPort, targetDB, []string{"public.orders"})
	waitCaughtUp(t, ctx, mt, id)

	// A second migration is rejected outright while the first exists.
	_, err = mt.CreateMigration(ctx, &migratorpb.CreateMigrationRequest{
		SourceDsn:      sourceDSN(srcPort),
		TargetDatabase: targetDB,
		Objects:        objs("public.widgets"),
	})
	require.Error(t, err, "a second migration must be rejected while one already exists")
	require.Contains(t, err.Error(), "only one migration is supported at a time")

	// The first migration is unaffected: it keeps streaming.
	tc := targetConn(t, ctx, primary, targetDB)
	defer tc.Close()
	_, err = sc.Query(ctx, "INSERT INTO public.orders (v) VALUES ('after-rejected-create')")
	require.NoError(t, err)
	require.Eventually(t, func() bool {
		n, ok := countRows(t, ctx, tc, "public.orders")
		return ok && n == 4
	}, 30*time.Second, 500*time.Millisecond, "the existing migration keeps streaming")

	// Once the first migration is dropped, creating a new one succeeds.
	_, err = mt.DropMigration(ctx, &migratorpb.DropMigrationRequest{Id: id, Force: true})
	require.NoError(t, err)
	idB := createAndStartMigration(t, ctx, mt, srcPort, targetDB, []string{"public.widgets"})
	waitCaughtUp(t, ctx, mt, idB)
}

// TestDDLReplicationExport proves DDL capture follows the publisher across a
// direction switch: after switching to EXPORT (the Multigres target becomes the
// publisher), a schema change on the target replicates OUT to the old database,
// scoped to the migration's tables — a change on a non-migrated table does not.
func TestDDLReplicationExport(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping Multigres Migrator switch e2e in short mode")
	}
	if !utils.HasPostgreSQLBinaries() {
		t.Skip("PostgreSQL client/server binaries not on PATH")
	}
	ctx := t.Context()

	setup, cleanup := shardsetup.NewIsolated(
		t,
		shardsetup.WithMultipoolerCount(2),
		// EXPORT makes the Multigres target the logical publisher, which needs the
		// slot-based-replication admission (matching targetConnInfo's guardrail).
		shardsetup.WithMultipoolerExtraArgs("--enable-slot-based-replication=true"),
	)
	defer cleanup()
	primary := setup.GetPrimary(t)
	shardsetup.WaitForManagerReady(t, primary.Multipooler)
	targetDB := waitForPrimaryDB(t, ctx, setup)

	srcPort := startStandaloneSource(t)
	seedSource(t, ctx, srcPort)

	mt, mtClose := migrationClient(t, primary)
	defer mtClose()

	id := createAndStartMigration(t, ctx, mt, srcPort, targetDB, []string{"public.orders"})
	waitCaughtUp(t, ctx, mt, id)

	tc := targetConn(t, ctx, primary, targetDB)
	defer tc.Close()

	// public.untracked is created on the target BEFORE the EXPORT switch: once
	// activated, the target becomes the publisher and CREATE TABLE while
	// capturing is rejected outright (see below), so an unrelated table used
	// later to prove non-migrated DDL doesn't replicate must already exist.
	_, err := tc.Query(ctx, "CREATE TABLE public.untracked (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, x text)")
	require.NoError(t, err)

	// Activate (switch to EXPORT): Multigres becomes the publisher, so DDL capture
	// moves to the target and apply to the old database.
	exportResp, err := mt.ActivateMigration(ctx, &migratorpb.ActivateMigrationRequest{Id: id})
	require.NoError(t, err)
	require.Equal(t, migratorpb.MigrationDirection_MIGRATION_DIRECTION_EXPORT, exportResp.GetMigration().GetActiveDirection())

	// A schema change on the migrated table on the Multigres target must reach the
	// old database.
	_, err = tc.Query(ctx, "ALTER TABLE public.orders ADD COLUMN exp_note text")
	require.NoError(t, err)
	require.Eventually(t, func() bool {
		sc := dialSource(t, ctx, srcPort)
		defer sc.Close()
		return columnsOf(t, ctx, sc, "public", "orders") == "id,v,exp_note"
	}, 30*time.Second, 500*time.Millisecond, "EXPORT: target DDL on a migrated table must reach the old database")

	// A schema change on a NON-migrated table on the target must NOT reach the old
	// database. ALTER the unrelated table created before the switch, then push a
	// migrated-table write after it and wait for that to land as a barrier.
	for _, stmt := range []string{
		"ALTER TABLE public.untracked ADD COLUMN y text",
		"INSERT INTO public.orders (v, exp_note) VALUES ('z', 'barrier')",
	} {
		_, err = tc.Query(ctx, stmt)
		require.NoError(t, err, stmt)
	}
	require.Eventually(t, func() bool {
		sc := dialSource(t, ctx, srcPort)
		defer sc.Close()
		n, ok := countRows(t, ctx, sc, "public.orders")
		return ok && n == 4
	}, 30*time.Second, 500*time.Millisecond, "EXPORT: later migrated write must land (barrier)")
	sc := dialSource(t, ctx, srcPort)
	defer sc.Close()
	require.Equal(t, "", columnsOf(t, ctx, sc, "public", "untracked"),
		"EXPORT: DDL on a non-migrated table must not reach the old database")

	// CREATE TABLE on the target is rejected outright now that it is capturing
	// as the EXPORT publisher, the mirror of the IMPORT-side rejection.
	_, err = tc.Query(ctx, "CREATE TABLE public.new_thing (id int)")
	require.Error(t, err, "EXPORT: CREATE TABLE must be rejected while the target is capturing")
	require.Contains(t, err.Error(), "CREATE TABLE is not allowed")
	_, err = tc.Query(ctx, "INSERT INTO public.orders (v, exp_note) VALUES ('zz', 'barrier2')")
	require.NoError(t, err)
	require.Eventually(t, func() bool {
		sc := dialSource(t, ctx, srcPort)
		defer sc.Close()
		n, ok := countRows(t, ctx, sc, "public.orders")
		return ok && n == 5
	}, 30*time.Second, 500*time.Millisecond, "EXPORT: streaming must continue after a rejected CREATE TABLE")

	_, err = mt.DropMigration(ctx, &migratorpb.DropMigrationRequest{Id: id, Force: true})
	require.NoError(t, err)
}

// createAndStartMigration creates and starts an IMPORT migration for the given
// tables and returns its id.
func createAndStartMigration(t *testing.T, ctx context.Context, mt migratorpb.MigratorClient, srcPort int, targetDB string, tables []string) int64 {
	t.Helper()
	createResp, err := mt.CreateMigration(ctx, &migratorpb.CreateMigrationRequest{
		SourceDsn:      sourceDSN(srcPort),
		TargetDatabase: targetDB,
		Objects:        objs(tables...),
	})
	require.NoError(t, err)
	id := createResp.GetMigration().GetId()
	startResp, err := mt.StartMigration(ctx, &migratorpb.StartMigrationRequest{Id: id})
	require.NoError(t, err, "start; last_error=%s", startResp.GetMigration().GetLastError())
	return id
}

// waitCaughtUp blocks until the migration reports caught up.
func waitCaughtUp(t *testing.T, ctx context.Context, mt migratorpb.MigratorClient, id int64) {
	t.Helper()
	require.Eventually(t, func() bool {
		resp, err := mt.GetMigrations(ctx, &migratorpb.GetMigrationsRequest{Id: id})
		return err == nil && len(resp.GetMigrations()) == 1 && resp.GetMigrations()[0].GetCaughtUp()
	}, 60*time.Second, 500*time.Millisecond, "migration %d must catch up", id)
}

// ddlLogCount returns the number of rows in multigres.ddl_log for the given
// table_name. The test connection authenticates as the postgres superuser, so
// it can read the superuser-only sidecar table.
func ddlLogCount(t *testing.T, ctx context.Context, conn *client.Conn, table string) int {
	t.Helper()
	res, err := conn.Query(ctx,
		"SELECT count(*) FROM multigres.ddl_log WHERE table_name = '"+table+"'")
	require.NoError(t, err)
	require.NotEmpty(t, res)
	require.NotEmpty(t, res[0].Rows)
	n, err := strconv.Atoi(string(res[0].Rows[0].Values[0]))
	require.NoError(t, err)
	return n
}
