package asthelpergen

import (
	"go/types"
	"strings"

	"github.com/dave/jennifer/jen"
)

const equalsName = "Equals"

// equalsGen creates the deep equality functions for the AST. Like cloneGen it
// starts from the root interface and discovers every type it has to compare
// along the way, emitting one EqualsX(a, b X) bool function per type.
//
// The comparison is structural: every field is compared, source positions
// included. Callers that need semantic equality must normalize the trees first.
//
// A type with an `Equal(T) bool` method is compared with that method instead of
// field by field. This is how values whose fields are not visible to the
// generated package (e.g. datum.Datum, aliased into ast) take part.
type equalsGen struct {
	// pkgPath is the import path of the package being generated. Fields whose
	// type is defined in a different package belong to another AST hierarchy
	// and are skipped, matching how clone and rewrite treat that boundary.
	pkgPath string
	file    *jen.File
}

var _ generator = (*equalsGen)(nil)

func newEqualsGen(pkgname, pkgPath string) *equalsGen {
	file := jen.NewFile(pkgname)
	addLicenseHeader(file)
	file.Comment("Code generated by asthelpergen. DO NOT EDIT.")

	return &equalsGen{
		pkgPath: pkgPath,
		file:    file,
	}
}

func (e *equalsGen) addFunc(name string, code *jen.Statement) {
	e.file.Add(jen.Commentf("%s does a deep equality check between the two inputs.", name))
	e.file.Add(code)
}

func (e *equalsGen) genFile(_ generatorSPI) (string, *jen.File) {
	return "ast_equals.go", e.file
}

// declareFunc returns `func EqualsX(a, b X) bool` and its name.
func (e *equalsGen) declareFunc(t types.Type, aArg, bArg string) (*jen.Statement, string) {
	typeString := types.TypeString(t, noQualifier)
	funcName := equalsName + printableTypeName(t)
	return jen.Func().Id(funcName).Params(jen.Id(aArg), jen.Id(bArg).Id(typeString)).Bool(), funcName
}

// compareValueType produces an expression that is true when a and b are equal
// (or unequal, when eq is false), adding t to the todo-list if it needs its own
// comparison function.
func (e *equalsGen) compareValueType(t types.Type, a, b *jen.Statement, eq bool, spi generatorSPI) *jen.Statement {
	var call *jen.Statement
	switch {
	case hasEqualMethod(t):
		call = a.Dot("Equal").Call(b)
	case isBasic(t):
		if eq {
			return a.Op("==").Add(b)
		}
		return a.Op("!=").Add(b)
	default:
		spi.addType(t)
		call = jen.Id(equalsName+printableTypeName(t)).Call(a, b)
	}
	if !eq {
		return jen.Op("!").Add(call)
	}
	return call
}

// interfaceMethod emits a type switch over every implementation of the
// interface. Values of different concrete types are never equal.
func (e *equalsGen) interfaceMethod(t types.Type, iface *types.Interface, spi generatorSPI) error {
	stmts := []jen.Code{
		jen.If(jen.Id("inA").Op("==").Nil().Op("&&").Id("inB").Op("==").Nil()).Block(jen.Return(jen.True())),
		jen.If(jen.Id("inA").Op("==").Nil().Op("||").Id("inB").Op("==").Nil()).Block(jen.Return(jen.False())),
	}

	var cases []jen.Code
	_ = spi.findImplementations(iface, func(impl types.Type) error {
		if _, ok := impl.Underlying().(*types.Interface); ok {
			return nil
		}
		typeString := types.TypeString(impl, noQualifier)
		cases = append(cases, jen.Case(jen.Id(typeString)).Block(
			jen.List(jen.Id("b"), jen.Id("ok")).Op(":=").Id("inB").Assert(jen.Id(typeString)),
			jen.If(jen.Op("!").Id("ok")).Block(jen.Return(jen.False())),
			jen.Return(e.compareValueType(impl, jen.Id("a"), jen.Id("b"), true, spi)),
		))
		return nil
	})

	cases = append(cases,
		jen.Default().Block(
			jen.Comment("this should never happen"),
			jen.Return(jen.False()),
		))

	stmts = append(stmts, jen.Switch(jen.Id("a").Op(":=").Id("inA").Assert(jen.Id("type"))).Block(cases...))

	funcDecl, funcName := e.declareFunc(t, "inA", "inB")
	e.addFunc(funcName, funcDecl.Block(stmts...))
	return nil
}

// structMethod handles struct values by comparing every field.
func (e *equalsGen) structMethod(t types.Type, strct *types.Struct, spi generatorSPI) error {
	funcDecl, funcName := e.declareFunc(t, "a", "b")
	if hasEqualMethod(t) {
		e.addFunc(funcName, funcDecl.Block(jen.Return(jen.Id("a").Dot("Equal").Call(jen.Id("b")))))
		return nil
	}
	e.addFunc(funcName, funcDecl.Block(jen.Return(e.compareAllStructFields(strct, spi))))
	return nil
}

// ptrToStructMethod handles pointers to structs: identical or both-nil pointers
// are equal, otherwise the pointees are compared.
func (e *equalsGen) ptrToStructMethod(t types.Type, strct *types.Struct, spi generatorSPI) error {
	elem := t.Underlying().(*types.Pointer).Elem()
	var cmp jen.Code
	if hasEqualMethod(elem) {
		cmp = jen.Id("a").Dot("Equal").Call(jen.Op("*").Id("b"))
	} else {
		cmp = e.compareAllStructFields(strct, spi)
	}
	funcDecl, funcName := e.declareFunc(t, "a", "b")
	e.addFunc(funcName, funcDecl.Block(
		jen.If(jen.Id("a").Op("==").Id("b")).Block(jen.Return(jen.True())),
		jen.If(jen.Id("a").Op("==").Nil().Op("||").Id("b").Op("==").Nil()).Block(jen.Return(jen.False())),
		jen.Return(cmp),
	))
	return nil
}

// compareAllStructFields builds `a.F1 == b.F1 && EqualsX(a.F2, b.F2) && ...`,
// with the cheap basic-typed comparisons first so mismatches short-circuit
// before any recursion.
func (e *equalsGen) compareAllStructFields(strct *types.Struct, spi generatorSPI) jen.Code {
	var basics, others []*jen.Statement
	for field := range strct.Fields() {
		if strings.HasPrefix(field.Name(), "_") {
			continue
		}
		// Foreign-package fields belong to another AST hierarchy whose
		// implementations this package cannot see (e.g.
		// plpgsqlast.PLpgSQL_expr.Parsed is an ast.Stmt). They are excluded
		// from the comparison, the same boundary clone and rewrite draw.
		if fp := typePackagePath(field.Type()); fp != "" && fp != e.pkgPath {
			continue
		}
		pred := e.compareValueType(field.Type(), jen.Id("a").Dot(field.Name()), jen.Id("b").Dot(field.Name()), true, spi)
		if isBasic(field.Type()) {
			basics = append(basics, pred)
		} else {
			others = append(others, pred)
		}
	}

	var ret *jen.Statement
	for _, pred := range append(basics, others...) {
		if ret == nil {
			ret = pred
		} else {
			ret = ret.Op("&&").Line().Add(pred)
		}
	}
	if ret == nil {
		return jen.True()
	}
	return ret
}

// ptrToBasicMethod handles pointers to basic types by comparing the pointees.
func (e *equalsGen) ptrToBasicMethod(t types.Type, _ *types.Basic, _ generatorSPI) error {
	funcDecl, funcName := e.declareFunc(t, "a", "b")
	e.addFunc(funcName, funcDecl.Block(
		jen.If(jen.Id("a").Op("==").Id("b")).Block(jen.Return(jen.True())),
		jen.If(jen.Id("a").Op("==").Nil().Op("||").Id("b").Op("==").Nil()).Block(jen.Return(jen.False())),
		jen.Return(jen.Op("*").Id("a").Op("==").Op("*").Id("b")),
	))
	return nil
}

// sliceMethod handles slices element by element. A nil slice equals an empty
// one: both hold no elements.
func (e *equalsGen) sliceMethod(t types.Type, slice *types.Slice, spi generatorSPI) error {
	funcDecl, funcName := e.declareFunc(t, "a", "b")
	e.addFunc(funcName, funcDecl.Block(
		jen.If(jen.Len(jen.Id("a")).Op("!=").Len(jen.Id("b"))).Block(jen.Return(jen.False())),
		jen.For(jen.Id("i").Op(":=").Range().Id("a")).Block(
			jen.If(e.compareValueType(slice.Elem(), jen.Id("a").Index(jen.Id("i")), jen.Id("b").Index(jen.Id("i")), false, spi)).Block(
				jen.Return(jen.False()),
			),
		),
		jen.Return(jen.True()),
	))
	return nil
}

// basicMethod emits nothing: basic values are compared inline with ==.
func (e *equalsGen) basicMethod(types.Type, *types.Basic, generatorSPI) error { return nil }

// hasEqualMethod reports whether values of t have an `Equal(T) bool` method.
func hasEqualMethod(t types.Type) bool {
	obj, _, _ := types.LookupFieldOrMethod(t, false, nil, "Equal")
	fn, ok := obj.(*types.Func)
	if !ok {
		return false
	}
	sig := fn.Type().(*types.Signature)
	return sig.Params().Len() == 1 && sig.Results().Len() == 1 &&
		types.Identical(sig.Params().At(0).Type(), t) &&
		types.Identical(sig.Results().At(0).Type(), types.Typ[types.Bool])
}
