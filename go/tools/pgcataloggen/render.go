func renderTypes(b *strings.Builder, rows []TypeRow) {
	b.WriteString("// Types holds every builtin pg_type row, sorted by OID.\nvar Types = []Type{\n")
	for _, t := range rows {
		fmt.Fprintf(b, "\t{Oid: %d, Name: %q, Len: %d, ByVal: %t, Category: %q, Preferred: %t, Input: %d, Output: %d, Receive: %d, Send: %d, Elem: %d, Array: %d, Collation: %d},\n",
			t.Oid, t.Name, t.Len, t.ByVal, rune(t.Category), t.Preferred, t.Input, t.Output, t.Receive, t.Send, t.Elem, t.Array, t.Collation)
	}
	b.WriteString("}\n")
}

func renderProcs(b *strings.Builder, rows []ProcRow) {
	b.WriteString("// Procs holds every builtin pg_proc row, sorted by OID.\nvar Procs = []Proc{\n")
	for _, p := range rows {
		args := "nil"
		if len(p.ArgTypes) > 0 {
			parts := make([]string, len(p.ArgTypes))
			for i, a := range p.ArgTypes {
				parts[i] = strconv.FormatUint(uint64(a), 10)
			}
			args = "[]Oid{" + strings.Join(parts, ", ") + "}"
		}
		fmt.Fprintf(b, "\t{Oid: %d, Name: %q, ArgTypes: %s, RetType: %d, Strict: %t, Volatile: %q, RetSet: %t, Kind: %q, Src: %q},\n",
			p.Oid, p.Name, args, p.RetType, p.Strict, rune(p.Volatile), p.RetSet, rune(p.Kind), p.Src)
	}
	b.WriteString("}\n")
}

func renderOperators(b *strings.Builder, rows []OperatorRow) {
	b.WriteString("// Operators holds every builtin pg_operator row, sorted by OID.\nvar Operators = []Operator{\n")
	for _, o := range rows {
		fmt.Fprintf(b, "\t{Oid: %d, Name: %q, Kind: %q, Left: %d, Right: %d, Result: %d, Commutator: %d, Negator: %d, Code: %d, CanMerge: %t, CanHash: %t},\n",
			o.Oid, o.Name, rune(o.Kind), o.Left, o.Right, o.Result, o.Commutator, o.Negator, o.Code, o.CanMerge, o.CanHash)
	}
	b.WriteString("}\n")
}

func renderCasts(b *strings.Builder, rows []CastRow) {
	b.WriteString("// Casts holds every builtin pg_cast row, sorted by (Source, Target).\nvar Casts = []Cast{\n")
	for _, c := range rows {
		fmt.Fprintf(b, "\t{Source: %d, Target: %d, Func: %d, Context: %q, Method: %q},\n",
			c.Source, c.Target, c.Func, rune(c.Context), rune(c.Method))
	}
	b.WriteString("}\n")
}
