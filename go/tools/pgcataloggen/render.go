// GenCommand is the command stamped into generated headers.
const GenCommand = "go run ./go/tools/pgcataloggen/main"

// Render writes the four generated table files into outDir.
func Render(cat *Catalog, outDir string) error {
	files := []struct {
		name   string
		source string
		render func(*strings.Builder)
	}{
		{
			name:   "types_generated.go",
			source: "pg_type.dat",
			render: func(b *strings.Builder) { renderTypes(b, cat.Types) },
		},
		{
			name:   "procs_generated.go",
			source: "pg_proc.dat",
			render: func(b *strings.Builder) { renderProcs(b, cat.Procs) },
		},
		{
			name:   "operators_generated.go",
			source: "pg_operator.dat",
			render: func(b *strings.Builder) { renderOperators(b, cat.Operators) },
		},
		{
			name:   "casts_generated.go",
			source: "pg_cast.dat",
			render: func(b *strings.Builder) { renderCasts(b, cat.Casts) },
		},
	}
	for _, f := range files {
		var b strings.Builder
		writeHeader(&b, f.source)
		f.render(&b)
		src, err := format.Source([]byte(b.String()))
		if err != nil {
			return fmt.Errorf("formatting %s: %w", f.name, err)
		}
		if err := os.WriteFile(filepath.Join(outDir, f.name), src, 0o644); err != nil {
			return err
		}
	}
	return nil
}

