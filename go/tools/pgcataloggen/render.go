// GenCommand is the command stamped into generated headers.
const GenCommand = "go run ./go/tools/pgcataloggen/main"

// Render writes the generated files: the catalog tables into catalogDir, the
// Oid constants + name table into pgoidDir, and the constant re-exports into
// astDir.
func Render(cat *Catalog, catalogDir, pgoidDir, astDir string) error {
	files := []struct {
		dir    string
		name   string
		pkg    string
		source string
		render func(*strings.Builder)
	}{
		{
			dir: catalogDir, name: "types_generated.go", pkg: "pgcatalog",
			source: "pg_type.dat",
			render: func(b *strings.Builder) { renderTypes(b, cat.Types) },
		},
		{
			dir: catalogDir, name: "procs_generated.go", pkg: "pgcatalog",
			source: "pg_proc.dat",
			render: func(b *strings.Builder) { renderProcs(b, cat.Procs) },
		},
		{
			dir: catalogDir, name: "operators_generated.go", pkg: "pgcatalog",
			source: "pg_operator.dat",
			render: func(b *strings.Builder) { renderOperators(b, cat.Operators) },
		},
		{
			dir: catalogDir, name: "casts_generated.go", pkg: "pgcatalog",
			source: "pg_cast.dat",
			render: func(b *strings.Builder) { renderCasts(b, cat.Casts) },
		},
		{
			dir: pgoidDir, name: "oids_generated.go", pkg: "pgoid",
			source: "pg_type.dat",
			render: func(b *strings.Builder) { renderOids(b, cat.Types) },
		},
		{
			dir: astDir, name: "oids_generated.go", pkg: "ast",
			source: "pg_type.dat",
			render: func(b *strings.Builder) { renderAstOids(b, cat.Types) },
		},
	}
	for _, f := range files {
		var b strings.Builder
		writeHeader(&b, f.pkg, f.source)
		f.render(&b)
		src, err := format.Source([]byte(b.String()))
		if err != nil {
			return fmt.Errorf("formatting %s: %w", f.name, err)
		}
		if err := os.WriteFile(filepath.Join(f.dir, f.name), src, 0o644); err != nil {
			return err
		}
	}
	return nil
}

